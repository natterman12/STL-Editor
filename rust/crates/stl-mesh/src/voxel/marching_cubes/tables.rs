/// A lookup table: `get2(i, j)` is `values[i * l1 + j]`, `get3(i, j, k)` is
/// `values[(i * l1 + j) * l2 + k]`, as `Lut` in `_marching_cubes_lewiner_cy.pyx`.
pub struct Lut {
    pub l1: usize,
    pub l2: usize,
    pub values: &'static [i8],
}

impl Lut {
    #[inline]
    pub fn get1(&self, i0: usize) -> i32 {
        self.values[i0] as i32
    }

    #[inline]
    pub fn get2(&self, i0: usize, i1: usize) -> i32 {
        self.values[i0 * self.l1 + i1] as i32
    }

    #[inline]
    pub fn get3(&self, i0: usize, i1: usize, i2: usize) -> i32 {
        self.values[i0 * self.l1 * self.l2 + i1 * self.l2 + i2] as i32
    }
}

